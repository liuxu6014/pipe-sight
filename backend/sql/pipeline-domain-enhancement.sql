-- PipeSight 最终业务库（采集与内容域，MySQL 8+）

CREATE TABLE IF NOT EXISTS data_sources (
  source_id VARCHAR(64) NOT NULL COMMENT '数据源ID',
  source_code VARCHAR(100) NOT NULL COMMENT '稳定的数据源编码',
  name VARCHAR(255) NOT NULL COMMENT '数据源名称',
  source_type VARCHAR(32) NOT NULL COMMENT '数据源类型',
  endpoint VARCHAR(1000) NULL COMMENT '数据源入口地址',
  adapter_key VARCHAR(128) NOT NULL COMMENT '采集适配器标识',
  schedule_cron VARCHAR(100) NULL COMMENT '调度表达式',
  status VARCHAR(32) NOT NULL DEFAULT 'active' COMMENT '生命周期状态',
  enabled BOOLEAN NOT NULL DEFAULT TRUE COMMENT '是否允许执行采集',
  config_json JSON NOT NULL COMMENT '采集规则与增量配置',
  handoff_mode VARCHAR(16) NOT NULL DEFAULT 'external' COMMENT '处理模式：local或external',
  processor_source_code VARCHAR(128) NULL COMMENT '外部处理系统来源编码',
  last_run_time DATETIME NULL COMMENT '最近采集时间',
  last_run_status VARCHAR(32) NULL COMMENT '最近采集状态',
  success_count INT NOT NULL DEFAULT 0 COMMENT '累计成功次数',
  failure_count INT NOT NULL DEFAULT 0 COMMENT '累计失败次数',
  consecutive_failures INT NOT NULL DEFAULT 0 COMMENT '连续失败次数',
  collection_lease_owner VARCHAR(128) NULL COMMENT '采集执行器租约持有者',
  collection_lease_until DATETIME NULL COMMENT '采集执行器租约到期时间',
  owner_id BIGINT NULL COMMENT '负责人ID',
  create_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  update_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
  PRIMARY KEY (source_id),
  CONSTRAINT uk_data_sources_code UNIQUE (source_code),
  CONSTRAINT ck_data_sources_status CHECK (status IN ('active', 'inactive')),
  CONSTRAINT ck_data_sources_handoff_mode CHECK (handoff_mode IN ('local', 'external')),
  CONSTRAINT ck_data_sources_counters CHECK (success_count >= 0 AND failure_count >= 0 AND consecutive_failures >= 0),
  CONSTRAINT fk_data_sources_user FOREIGN KEY (owner_id) REFERENCES sys_user(user_id) ON DELETE SET NULL,
  KEY idx_data_sources_type_status (source_type, status),
  KEY idx_data_sources_owner (owner_id),
  KEY idx_data_sources_collection_lease (enabled, status, collection_lease_until, update_time)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='数据来源配置表';

