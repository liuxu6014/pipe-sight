-- PipeSight 最终业务库（采集与内容域，MySQL 8+）

CREATE TABLE IF NOT EXISTS data_sources (
  source_id VARCHAR(64) NOT NULL COMMENT '数据源ID',
  source_code VARCHAR(100) NOT NULL COMMENT '稳定的数据源编码',
  name VARCHAR(255) NOT NULL COMMENT '数据源名称',
  source_type VARCHAR(32) NOT NULL COMMENT '数据源类型',
  endpoint VARCHAR(1000) NULL COMMENT '数据源入口地址',
  adapter_key VARCHAR(128) NOT NULL COMMENT '采集适配器标识',
  schedule_cron VARCHAR(100) NULL COMMENT '调度表达式',
  status VARCHAR(32) NOT NULL DEFAULT 'active' COMMENT '生命周期状态',
  enabled BOOLEAN NOT NULL DEFAULT TRUE COMMENT '是否允许执行采集',
  config_json JSON NOT NULL COMMENT '采集规则与增量配置',
  handoff_mode VARCHAR(16) NOT NULL DEFAULT 'external' COMMENT '处理模式：local或external',
  processor_source_code VARCHAR(128) NULL COMMENT '外部处理系统来源编码',
  last_run_time DATETIME NULL COMMENT '最近采集时间',
  last_run_status VARCHAR(32) NULL COMMENT '最近采集状态',
  success_count INT NOT NULL DEFAULT 0 COMMENT '累计成功次数',
  failure_count INT NOT NULL DEFAULT 0 COMMENT '累计失败次数',
  consecutive_failures INT NOT NULL DEFAULT 0 COMMENT '连续失败次数',
  owner_id BIGINT NULL COMMENT '负责人ID',
  create_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  update_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
  PRIMARY KEY (source_id),
  CONSTRAINT uk_data_sources_code UNIQUE (source_code),
  CONSTRAINT ck_data_sources_status CHECK (status IN ('active', 'inactive')),
  CONSTRAINT ck_data_sources_handoff_mode CHECK (handoff_mode IN ('local', 'external')),
  CONSTRAINT ck_data_sources_counters CHECK (success_count >= 0 AND failure_count >= 0 AND consecutive_failures >= 0),
  CONSTRAINT fk_data_sources_user FOREIGN KEY (owner_id) REFERENCES sys_user(user_id) ON DELETE SET NULL,
  KEY idx_data_sources_type_status (source_type, status),
  KEY idx_data_sources_owner (owner_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='数据来源配置表';

CREATE TABLE IF NOT EXISTS pipeline_template_versions (
  template_id VARCHAR(64) NOT NULL COMMENT '模板版本ID',
  template_key VARCHAR(64) NOT NULL COMMENT '稳定模板编码',
  code VARCHAR(32) NOT NULL COMMENT '模板展示编码',
  category VARCHAR(32) NOT NULL COMMENT '模板分类',
  report_type VARCHAR(64) NOT NULL COMMENT '报告类型',
  name VARCHAR(255) NOT NULL COMMENT '模板名称',
  description VARCHAR(1000) NOT NULL DEFAULT '' COMMENT '模板说明',
  color VARCHAR(32) NOT NULL DEFAULT '#2764e7' COMMENT '展示颜色',
  version_label VARCHAR(32) NOT NULL COMMENT '展示版本号',
  version_no INT NOT NULL DEFAULT 1 COMMENT '版本序号',
  status VARCHAR(32) NOT NULL DEFAULT 'draft' COMMENT '版本状态',
  formats JSON NOT NULL COMMENT '支持的输出格式',
  sections JSON NOT NULL COMMENT '章节结构',
  usage_count INT NOT NULL DEFAULT 0 COMMENT '使用次数快照',
  operator_id BIGINT NULL COMMENT '操作用户ID',
  operator_name VARCHAR(64) NOT NULL DEFAULT '' COMMENT '操作用户名称快照',
  published_at DATETIME NULL COMMENT '发布时间',
  create_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  update_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
  PRIMARY KEY (template_id),
  CONSTRAINT uk_pipeline_template_key_version UNIQUE (template_key, version_no),
  CONSTRAINT ck_pipeline_template_status CHECK (status IN ('draft', 'published', 'retired')),
  CONSTRAINT ck_pipeline_template_version_no CHECK (version_no >= 1),
  CONSTRAINT fk_pipeline_template_user FOREIGN KEY (operator_id) REFERENCES sys_user(user_id) ON DELETE SET NULL,
  KEY idx_pipeline_template_category_status (category, status),
  KEY idx_pipeline_template_key_time (template_key, update_time)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='管网科研与情报模板版本表';

CREATE TABLE IF NOT EXISTS collection_runs (
  run_id VARCHAR(64) NOT NULL COMMENT '运行ID',
  source_id VARCHAR(64) NOT NULL COMMENT '数据源ID',
  scheduler_job_id BIGINT NULL COMMENT '调度任务ID',
  trigger_type VARCHAR(32) NOT NULL DEFAULT 'schedule' COMMENT '触发类型',
  status VARCHAR(32) NOT NULL DEFAULT 'queued' COMMENT '运行状态',
  config_snapshot JSON NOT NULL COMMENT '本次执行配置快照',
  started_at DATETIME NULL COMMENT '开始时间',
  finished_at DATETIME NULL COMMENT '结束时间',
  fetched_count INT NOT NULL DEFAULT 0 COMMENT '抓取条数',
  inserted_count INT NOT NULL DEFAULT 0 COMMENT '新增条数',
  updated_count INT NOT NULL DEFAULT 0 COMMENT '更新条数',
  duplicate_count INT NOT NULL DEFAULT 0 COMMENT '去重条数',
  failed_count INT NOT NULL DEFAULT 0 COMMENT '失败条数',
  handoff_status VARCHAR(32) NOT NULL DEFAULT 'pending' COMMENT '外部处理状态',
  handoff_batch_id VARCHAR(64) NULL COMMENT '外部处理批次ID',
  handoff_count INT NOT NULL DEFAULT 0 COMMENT '提交外部处理条数',
  handoff_processed_count INT NOT NULL DEFAULT 0 COMMENT '外部处理完成条数',
  handoff_failed_count INT NOT NULL DEFAULT 0 COMMENT '外部处理失败条数',
  handoff_time DATETIME NULL COMMENT '最近外部处理回执时间',
  handoff_error TEXT NULL COMMENT '外部处理错误摘要',
  error_message TEXT NULL COMMENT '错误信息',
  checkpoint_json JSON NOT NULL COMMENT '断点信息',
  create_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  update_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
  PRIMARY KEY (run_id),
  CONSTRAINT ck_collection_runs_trigger_type CHECK (trigger_type IN ('schedule', 'manual', 'retry')),
  CONSTRAINT ck_collection_runs_status CHECK (status IN ('queued', 'running', 'success', 'failed', 'cancelled')),
  CONSTRAINT ck_collection_runs_counters CHECK (fetched_count >= 0 AND inserted_count >= 0 AND updated_count >= 0 AND duplicate_count >= 0 AND failed_count >= 0 AND handoff_count >= 0 AND handoff_processed_count >= 0 AND handoff_failed_count >= 0),
  CONSTRAINT ck_collection_runs_handoff_status CHECK (handoff_status IN ('pending', 'dispatched', 'processing', 'completed', 'partial', 'failed')),
  CONSTRAINT fk_collection_runs_sources FOREIGN KEY (source_id) REFERENCES data_sources(source_id) ON DELETE RESTRICT,
  CONSTRAINT fk_collection_runs_jobs FOREIGN KEY (scheduler_job_id) REFERENCES sys_job(job_id) ON DELETE SET NULL,
  KEY idx_collection_runs_source_time (source_id, create_time),
  KEY idx_collection_runs_status_time (status, create_time),
  KEY idx_collection_runs_handoff_status_time (handoff_status, create_time)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='采集运行记录表';

CREATE TABLE IF NOT EXISTS news_articles (
  article_id VARCHAR(64) NOT NULL COMMENT '文章ID',
  article_type VARCHAR(32) NOT NULL COMMENT '文章类型：news或wechat',
  title VARCHAR(500) NOT NULL COMMENT '标题',
  canonical_url VARCHAR(1500) NULL COMMENT '规范化地址',
  url_hash VARCHAR(128) NULL COMMENT '规范化地址指纹',
  source_id VARCHAR(64) NULL COMMENT '数据源ID',
  source_name VARCHAR(255) NULL COMMENT '数据源名称快照',
  collection_run_id VARCHAR(64) NULL COMMENT '采集运行ID',
  author_text VARCHAR(500) NULL COMMENT '作者',
  published_time DATETIME NULL COMMENT '发布时间',
  discovered_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '发现时间',
  language VARCHAR(16) NOT NULL DEFAULT 'zh-CN' COMMENT '语言',
  summary TEXT NULL COMMENT '摘要',
  body LONGTEXT NULL COMMENT '正文',
  article_hash VARCHAR(128) NULL COMMENT '正文指纹',
  relevance_score INT NOT NULL DEFAULT 0 COMMENT '相关性评分',
  review_status VARCHAR(32) NOT NULL DEFAULT 'pending' COMMENT '审核状态',
  permission_scope VARCHAR(32) NOT NULL DEFAULT 'public' COMMENT '可见范围',
  tags JSON NOT NULL COMMENT '标签',
  metadata_json JSON NOT NULL COMMENT '扩展元数据',
  analysis_version VARCHAR(64) NULL COMMENT '当前分析版本',
  handoff_status VARCHAR(32) NOT NULL DEFAULT 'pending' COMMENT '外部处理状态',
  handoff_batch_id VARCHAR(64) NULL COMMENT '外部处理批次ID',
  handoff_record_id VARCHAR(128) NULL COMMENT '外部处理记录ID',
  handoff_trace_id VARCHAR(64) NULL COMMENT '外部Prompt血缘或处理追踪ID',
  handoff_version VARCHAR(64) NULL COMMENT '外部处理版本',
  handoff_result_json JSON NOT NULL COMMENT '外部处理结果快照',
  handoff_time DATETIME NULL COMMENT '外部处理回执时间',
  handoff_error TEXT NULL COMMENT '外部处理错误摘要',
  version_no INT NOT NULL DEFAULT 1 COMMENT '内容版本号',
  create_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  update_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
  PRIMARY KEY (article_id),
  CONSTRAINT uk_news_articles_hash UNIQUE (article_hash),
  CONSTRAINT uk_news_articles_url_hash UNIQUE (url_hash),
  CONSTRAINT ck_news_articles_type CHECK (article_type IN ('news', 'wechat')),
  CONSTRAINT ck_news_articles_relevance CHECK (relevance_score BETWEEN 0 AND 100),
  CONSTRAINT ck_news_articles_review_status CHECK (review_status IN ('pending', 'approved', 'rejected')),
  CONSTRAINT ck_news_articles_permission_scope CHECK (permission_scope IN ('private', 'public')),
  CONSTRAINT ck_news_articles_handoff_status CHECK (handoff_status IN ('pending', 'dispatched', 'processing', 'completed', 'partial', 'failed', 'rejected')),
  CONSTRAINT fk_news_articles_sources FOREIGN KEY (source_id) REFERENCES data_sources(source_id) ON DELETE SET NULL,
  CONSTRAINT fk_news_articles_runs FOREIGN KEY (collection_run_id) REFERENCES collection_runs(run_id) ON DELETE SET NULL,
  KEY idx_news_articles_type_time (article_type, published_time),
  KEY idx_news_articles_source_time (source_id, published_time),
  KEY idx_news_articles_review_time (review_status, published_time),
  KEY idx_news_articles_handoff_status_time (handoff_status, update_time)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='科技资讯文章表';

CREATE TABLE IF NOT EXISTS papers (
  paper_id VARCHAR(64) NOT NULL COMMENT '论文ID',
  title VARCHAR(500) NOT NULL COMMENT '论文标题',
  canonical_url VARCHAR(1500) NULL COMMENT '论文来源地址',
  source_id VARCHAR(64) NULL COMMENT '数据源ID',
  source_name VARCHAR(255) NULL COMMENT '数据源名称快照',
  collection_run_id VARCHAR(64) NULL COMMENT '采集运行ID',
  authors VARCHAR(1000) NULL COMMENT '作者展示文本',
  authors_json JSON NOT NULL COMMENT '结构化作者与机构',
  keywords JSON NOT NULL COMMENT '论文关键词',
  doi VARCHAR(255) NULL COMMENT '原始DOI',
  doi_normalized VARCHAR(255) NULL COMMENT '规范化DOI',
  external_id VARCHAR(255) NULL COMMENT '外部数据库ID',
  journal VARCHAR(255) NULL COMMENT '期刊或会议',
  publisher VARCHAR(255) NULL COMMENT '出版方',
  publication_year INT NULL COMMENT '发表年份',
  volume VARCHAR(64) NULL COMMENT '卷',
  issue VARCHAR(64) NULL COMMENT '期',
  pages VARCHAR(64) NULL COMMENT '页码',
  abstract_text TEXT NULL COMMENT '论文摘要',
  full_text_url VARCHAR(1500) NULL COMMENT '合法全文地址',
  citation_count INT NOT NULL DEFAULT 0 COMMENT '引用次数',
  open_access_status VARCHAR(32) NOT NULL DEFAULT 'unknown' COMMENT '开放获取状态',
  full_text_status VARCHAR(32) NOT NULL DEFAULT 'unknown' COMMENT '全文状态',
  review_status VARCHAR(32) NOT NULL DEFAULT 'pending' COMMENT '审核状态',
  permission_scope VARCHAR(32) NOT NULL DEFAULT 'public' COMMENT '可见范围',
  tags JSON NOT NULL COMMENT '标签',
  metadata_json JSON NOT NULL COMMENT '扩展元数据',
  handoff_status VARCHAR(32) NOT NULL DEFAULT 'pending' COMMENT '外部处理状态',
  handoff_batch_id VARCHAR(64) NULL COMMENT '外部处理批次ID',
  handoff_record_id VARCHAR(128) NULL COMMENT '外部处理记录ID',
  handoff_trace_id VARCHAR(64) NULL COMMENT '外部Prompt血缘或处理追踪ID',
  handoff_version VARCHAR(64) NULL COMMENT '外部处理版本',
  handoff_result_json JSON NOT NULL COMMENT '外部处理结果快照',
  handoff_time DATETIME NULL COMMENT '外部处理回执时间',
  handoff_error TEXT NULL COMMENT '外部处理错误摘要',
  create_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  update_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
  PRIMARY KEY (paper_id),
  CONSTRAINT uk_papers_doi_normalized UNIQUE (doi_normalized),
  CONSTRAINT ck_papers_publication_year CHECK (publication_year IS NULL OR publication_year >= 1600),
  CONSTRAINT ck_papers_citation_count CHECK (citation_count >= 0),
  CONSTRAINT ck_papers_review_status CHECK (review_status IN ('pending', 'approved', 'rejected')),
  CONSTRAINT ck_papers_permission_scope CHECK (permission_scope IN ('private', 'public')),
  CONSTRAINT ck_papers_handoff_status CHECK (handoff_status IN ('pending', 'dispatched', 'processing', 'completed', 'partial', 'failed', 'rejected')),
  CONSTRAINT fk_papers_sources FOREIGN KEY (source_id) REFERENCES data_sources(source_id) ON DELETE SET NULL,
  CONSTRAINT fk_papers_runs FOREIGN KEY (collection_run_id) REFERENCES collection_runs(run_id) ON DELETE SET NULL,
  KEY idx_papers_year (publication_year),
  KEY idx_papers_journal (journal),
  KEY idx_papers_source_time (source_id, create_time),
  KEY idx_papers_handoff_status_time (handoff_status, update_time)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='论文资料表';

CREATE TABLE IF NOT EXISTS pipeline_prompt_versions (
  prompt_id VARCHAR(64) NOT NULL COMMENT '提示词版本ID',
  prompt_key VARCHAR(64) NOT NULL COMMENT '稳定提示词编码',
  scene VARCHAR(64) NOT NULL COMMENT '业务场景',
  name VARCHAR(255) NOT NULL COMMENT '提示词名称',
  description VARCHAR(1000) NOT NULL DEFAULT '' COMMENT '用途说明',
  system_prompt LONGTEXT NOT NULL COMMENT '系统提示词',
  user_prompt LONGTEXT NOT NULL COMMENT '用户提示词模板',
  version_no INT NOT NULL DEFAULT 1 COMMENT '版本号',
  status VARCHAR(32) NOT NULL DEFAULT 'draft' COMMENT '版本状态',
  test_status VARCHAR(32) NOT NULL DEFAULT 'untested' COMMENT '离线测试状态',
  test_result JSON NOT NULL COMMENT '最近一次测试结果',
  operator_id BIGINT NULL COMMENT '操作用户ID',
  operator_name VARCHAR(64) NOT NULL DEFAULT '' COMMENT '操作用户名称快照',
  published_at DATETIME NULL COMMENT '发布时间',
  create_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  update_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
  PRIMARY KEY (prompt_id),
  CONSTRAINT uk_pipeline_prompt_key_version UNIQUE (prompt_key, version_no),
  CONSTRAINT ck_pipeline_prompt_status CHECK (status IN ('draft', 'published', 'retired')),
  CONSTRAINT ck_pipeline_prompt_test_status CHECK (test_status IN ('untested', 'passed', 'failed')),
  CONSTRAINT ck_pipeline_prompt_version_no CHECK (version_no >= 1),
  CONSTRAINT fk_pipeline_prompt_operator FOREIGN KEY (operator_id) REFERENCES sys_user(user_id) ON DELETE SET NULL,
  KEY idx_pipeline_prompt_scene_status (scene, status),
  KEY idx_pipeline_prompt_key_time (prompt_key, update_time)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='管网模型提示词版本表';
