CREATE OR REPLACE FUNCTION news.set_updated_at()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    NEW.updated_at := now();
    RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION news.guard_prompt_version_immutable()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF OLD.status <> 'draft' AND NEW.status = 'draft' THEN
        RAISE EXCEPTION
            'Prompt version % cannot be reverted to draft after publish', OLD.prompt_version_id
            USING ERRCODE = 'check_violation';
    END IF;

    IF OLD.status <> 'draft'
       OR EXISTS (
            SELECT 1
            FROM news.prompt_usages u
            WHERE u.prompt_version_id = OLD.prompt_version_id
       ) THEN
        IF NEW.parent_prompt_version_id IS DISTINCT FROM OLD.parent_prompt_version_id
           OR NEW.prompt_key IS DISTINCT FROM OLD.prompt_key
           OR NEW.prompt_name IS DISTINCT FROM OLD.prompt_name
           OR NEW.prompt_type IS DISTINCT FROM OLD.prompt_type
           OR NEW.domain_id IS DISTINCT FROM OLD.domain_id
           OR NEW.category_id IS DISTINCT FROM OLD.category_id
           OR NEW.version_no IS DISTINCT FROM OLD.version_no
           OR NEW.system_prompt IS DISTINCT FROM OLD.system_prompt
           OR NEW.user_prompt IS DISTINCT FROM OLD.user_prompt
           OR NEW.template_variables IS DISTINCT FROM OLD.template_variables
           OR NEW.content_hash IS DISTINCT FROM OLD.content_hash
           OR NEW.derivation_note IS DISTINCT FROM OLD.derivation_note
           OR NEW.published_at IS DISTINCT FROM OLD.published_at THEN
            RAISE EXCEPTION
                'Prompt version % is immutable after publish or use', OLD.prompt_version_id
                USING ERRCODE = 'check_violation';
        END IF;
    END IF;
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_prompt_version_immutable ON news.prompt_versions;
CREATE TRIGGER trg_prompt_version_immutable
BEFORE UPDATE ON news.prompt_versions
FOR EACH ROW EXECUTE FUNCTION news.guard_prompt_version_immutable();

