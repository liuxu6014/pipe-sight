CREATE SCHEMA IF NOT EXISTS news AUTHORIZATION CURRENT_USER;
-- Adopt an older installation before CREATE TABLE IF NOT EXISTS can create a
-- second, empty physical table next to its legacy counterpart.
DO $processing_names$
DECLARE
    mapping record;
    old_kind "char";
BEGIN
    FOR mapping IN SELECT * FROM (VALUES
        ('hp_data_source', 'data_sources'), ('hp_domain', 'domains'),
        ('hp_topic', 'topics'), ('hp_news', 'articles'),
        ('sys_prompt_version', 'prompt_versions'),
        ('act_domain_topic_actions', 'domain_topic_rules'),
        ('news_prompt_usage', 'prompt_usages'), ('news_embedding', 'embeddings')
    ) AS names(old_name, new_name)
    LOOP
        SELECT c.relkind INTO old_kind FROM pg_class c
        JOIN pg_namespace n ON n.oid=c.relnamespace
        WHERE n.nspname='news' AND c.relname=mapping.old_name;
        IF old_kind IN ('r', 'p') THEN
            IF to_regclass(format('news.%I', mapping.new_name)) IS NOT NULL THEN
                RAISE EXCEPTION 'Both legacy and canonical objects exist: news.% / news.%', mapping.old_name, mapping.new_name;
            END IF;
            EXECUTE format('ALTER TABLE news.%I RENAME TO %I', mapping.old_name, mapping.new_name);
        END IF;
    END LOOP;
END
$processing_names$;
DO $$
DECLARE
    vector_schema text;
BEGIN
    SELECT n.nspname
      INTO vector_schema
      FROM pg_extension e
      JOIN pg_namespace n ON n.oid = e.extnamespace
     WHERE e.extname = 'vector';

    IF vector_schema IS NOT NULL AND vector_schema <> 'news' THEN
        EXECUTE 'ALTER EXTENSION vector SET SCHEMA news';
    END IF;
END
$$;
CREATE EXTENSION IF NOT EXISTS vector WITH SCHEMA news;
SET search_path = news, public;

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'content_type' AND typnamespace = 'news'::regnamespace) THEN
        CREATE TYPE news.content_type AS ENUM ('HTML', 'RSS', 'JSON', 'Other');
    END IF;
END
$$;

