-- PipeSight 最终业务库（核心域，MySQL 8+）

CREATE TABLE IF NOT EXISTS knowledge_files (
  file_id VARCHAR(64) NOT NULL COMMENT '知识文件ID',
  name VARCHAR(255) NOT NULL COMMENT '资料名称',
  category VARCHAR(64) NOT NULL DEFAULT '内部文献' COMMENT '资料分类',
  file_name VARCHAR(255) NULL COMMENT '存储文件名',
  file_path VARCHAR(500) NULL COMMENT '对象存储键或本地映射路径',
  file_url VARCHAR(1000) NULL COMMENT '受控文件访问地址',
  mime_type VARCHAR(128) NULL COMMENT '文件MIME类型',
  file_size BIGINT NOT NULL DEFAULT 0 COMMENT '文件大小',
  file_hash VARCHAR(128) NULL COMMENT '文件SHA-256',
  permission_scope VARCHAR(32) NOT NULL DEFAULT 'private' COMMENT '可见范围',
  allow_download BOOLEAN NOT NULL DEFAULT TRUE COMMENT '是否允许下载',
  allow_ai_use BOOLEAN NOT NULL DEFAULT TRUE COMMENT '是否允许用于AI',
  parse_status VARCHAR(32) NOT NULL DEFAULT 'queued' COMMENT '解析状态',
  parse_message VARCHAR(500) NULL COMMENT '解析说明',
  parse_attempt_count INT NOT NULL DEFAULT 0 COMMENT '解析尝试次数',
  parse_lease_owner VARCHAR(128) NULL COMMENT '解析执行器租约持有者',
  parse_lease_until DATETIME NULL COMMENT '解析执行器租约到期时间',
  parse_next_retry_at DATETIME NULL COMMENT '下次解析重试时间',
  scan_status VARCHAR(32) NOT NULL DEFAULT 'pending' COMMENT '安全扫描状态',
  scan_message VARCHAR(500) NULL COMMENT '安全扫描说明',
  scan_time DATETIME NULL COMMENT '安全扫描完成时间',
  scanner_name VARCHAR(128) NULL COMMENT '扫描器名称',
  summary TEXT NULL COMMENT '资料摘要',
  extracted_text LONGTEXT NULL COMMENT '完整提取文本',
  tags JSON NOT NULL COMMENT '标签',
  metadata_json JSON NOT NULL COMMENT '扩展元数据',
  version_no INT NOT NULL DEFAULT 1 COMMENT '资料版本号',
  owner_id BIGINT NOT NULL COMMENT '所有者ID',
  owner_name VARCHAR(64) NOT NULL COMMENT '所有者名称快照',
  create_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  update_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
  PRIMARY KEY (file_id),
  CONSTRAINT ck_knowledge_files_permission_scope CHECK (permission_scope IN ('private', 'public')),
  CONSTRAINT ck_knowledge_files_parse_status CHECK (parse_status IN ('queued', 'parsing', 'indexed', 'failed')),
  CONSTRAINT ck_knowledge_files_parse_attempt_count CHECK (parse_attempt_count >= 0),
  CONSTRAINT ck_knowledge_files_scan_status CHECK (scan_status IN ('pending', 'clean', 'quarantined', 'failed')),
  CONSTRAINT ck_knowledge_files_file_size CHECK (file_size >= 0),
  CONSTRAINT ck_knowledge_files_version_no CHECK (version_no >= 1),
  CONSTRAINT fk_knowledge_files_user FOREIGN KEY (owner_id) REFERENCES sys_user(user_id) ON DELETE RESTRICT,
  KEY idx_knowledge_files_owner_time (owner_id, update_time),
  KEY idx_knowledge_files_scope (permission_scope, update_time),
  KEY idx_knowledge_files_status_time (parse_status, update_time),
  KEY idx_knowledge_files_parse_dispatch (parse_status, scan_status, parse_next_retry_at, parse_lease_until, update_time),
  KEY idx_knowledge_files_scan_status_time (scan_status, update_time),
  KEY idx_knowledge_files_hash (file_hash)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='知识库文件表';

CREATE TABLE IF NOT EXISTS user_saved_items (
  saved_item_id BIGINT NOT NULL AUTO_INCREMENT COMMENT '收藏记录ID',
  user_id BIGINT NOT NULL COMMENT '用户ID',
  item_id VARCHAR(64) NOT NULL COMMENT '业务条目ID',
  item_type VARCHAR(32) NOT NULL COMMENT 'material、article、paper或report',
  action VARCHAR(16) NOT NULL COMMENT 'favorite或basket',
  title VARCHAR(500) NOT NULL COMMENT '标题快照',
  snapshot JSON NOT NULL COMMENT '条目快照',
  create_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  PRIMARY KEY (saved_item_id),
  CONSTRAINT uk_user_saved_items_target_action UNIQUE (user_id, item_type, item_id, action),
  CONSTRAINT ck_user_saved_items_item_type CHECK (item_type IN ('material', 'article', 'paper', 'report')),
  CONSTRAINT ck_user_saved_items_action CHECK (action IN ('favorite', 'basket')),
  CONSTRAINT fk_user_saved_items_user FOREIGN KEY (user_id) REFERENCES sys_user(user_id) ON DELETE CASCADE,
  KEY idx_user_saved_items_user_action_time (user_id, action, create_time),
  KEY idx_user_saved_items_target (item_type, item_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='用户收藏与资料篮表';

CREATE TABLE IF NOT EXISTS generation_tasks (
  task_id VARCHAR(64) NOT NULL COMMENT '生成任务ID',
  user_id BIGINT NOT NULL COMMENT '创建用户ID',
  owner_name VARCHAR(64) NOT NULL COMMENT '创建用户名称快照',
  title VARCHAR(500) NOT NULL COMMENT '任务名称',
  report_type VARCHAR(64) NOT NULL COMMENT '报告类型',
  template_id VARCHAR(64) NULL COMMENT '前端或代码内置模板编码快照',
  template_version VARCHAR(32) NULL COMMENT '模板版本显示值快照',
  status VARCHAR(32) NOT NULL DEFAULT 'queued' COMMENT '任务状态',
  current_stage VARCHAR(64) NOT NULL DEFAULT 'validating' COMMENT '当前阶段',
  progress INT NOT NULL DEFAULT 0 COMMENT '进度',
  config JSON NOT NULL COMMENT '任务输入和参数快照',
  selected_items JSON NOT NULL COMMENT '任务启动时的资料权威快照',
  outline JSON NOT NULL COMMENT '报告大纲',
  stages JSON NOT NULL COMMENT '阶段状态',
  logs JSON NOT NULL COMMENT '任务日志',
  attempt_count INT NOT NULL DEFAULT 0 COMMENT '执行尝试次数',
  lease_owner VARCHAR(128) NULL COMMENT '当前执行器租约持有者',
  lease_until DATETIME NULL COMMENT '当前执行器租约到期时间',
  next_retry_at DATETIME NULL COMMENT '下次重试时间',
  cancel_requested_at DATETIME NULL COMMENT '用户请求取消时间',
  error_message TEXT NULL COMMENT '错误信息',
  create_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  update_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
  PRIMARY KEY (task_id),
  CONSTRAINT ck_generation_tasks_status CHECK (status IN ('queued', 'running', 'completed', 'failed', 'dead_letter', 'cancelled')),
  CONSTRAINT ck_generation_tasks_progress CHECK (progress BETWEEN 0 AND 100),
  CONSTRAINT ck_generation_tasks_attempt_count CHECK (attempt_count >= 0),
  CONSTRAINT fk_generation_tasks_user FOREIGN KEY (user_id) REFERENCES sys_user(user_id) ON DELETE RESTRICT,
  KEY idx_generation_tasks_user_status_time (user_id, status, update_time),
  KEY idx_generation_tasks_dispatch (status, next_retry_at, lease_until, update_time),
  KEY idx_generation_tasks_cancel_dispatch (status, cancel_requested_at, lease_until, update_time)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='报告生成任务表';

CREATE TABLE IF NOT EXISTS digest_schedules (
  schedule_id VARCHAR(64) NOT NULL COMMENT '计划ID',
  user_id BIGINT NOT NULL COMMENT '创建用户ID',
  request_id VARCHAR(128) NULL COMMENT '客户端幂等请求标识',
  owner_name VARCHAR(64) NOT NULL COMMENT '创建用户名称快照',
  name VARCHAR(255) NOT NULL COMMENT '计划名称',
  report_type VARCHAR(32) NOT NULL COMMENT '日报、周报或月报',
  template_id VARCHAR(64) NOT NULL COMMENT '已发布模板编码',
  template_version VARCHAR(32) NULL COMMENT '模板版本快照',
  schedule_time VARCHAR(5) NOT NULL DEFAULT '08:00' COMMENT '本地执行时间HH:MM',
  config JSON NOT NULL COMMENT '生成筛选和内容配置快照',
  enabled BOOLEAN NOT NULL DEFAULT TRUE COMMENT '是否启用',
  next_run_time DATETIME NOT NULL COMMENT '下次执行时间',
  last_run_time DATETIME NULL COMMENT '最近一次调度时间',
  last_task_id VARCHAR(64) NULL COMMENT '最近生成任务ID',
  last_status VARCHAR(32) NULL COMMENT '最近一次调度状态',
  last_error TEXT NULL COMMENT '最近一次失败说明',
  failure_count INT NOT NULL DEFAULT 0 COMMENT '连续失败次数',
  lease_owner VARCHAR(128) NULL COMMENT '调度执行器租约持有者',
  lease_until DATETIME NULL COMMENT '调度执行器租约到期时间',
  create_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  update_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
  PRIMARY KEY (schedule_id),
  CONSTRAINT ck_digest_schedules_report_type CHECK (report_type IN ('daily', 'weekly', 'monthly')),
  CONSTRAINT ck_digest_schedules_last_status CHECK (last_status IS NULL OR last_status IN ('queued', 'no_data', 'skipped', 'failed')),
  CONSTRAINT ck_digest_schedules_failure_count CHECK (failure_count >= 0),
  CONSTRAINT fk_digest_schedules_user FOREIGN KEY (user_id) REFERENCES sys_user(user_id) ON DELETE CASCADE,
  CONSTRAINT fk_digest_schedules_task FOREIGN KEY (last_task_id) REFERENCES generation_tasks(task_id) ON DELETE SET NULL,
  UNIQUE KEY uk_digest_schedules_user_request (user_id, request_id),
  KEY idx_digest_schedules_dispatch (enabled, next_run_time, lease_until),
  KEY idx_digest_schedules_user_time (user_id, update_time)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='周期情报简报自动生成计划表';

CREATE TABLE IF NOT EXISTS reports (
  report_id VARCHAR(64) NOT NULL COMMENT '报告ID',
  source_task_id VARCHAR(64) NULL COMMENT '来源任务ID；任务与报告关系的唯一权威字段',
  user_id BIGINT NOT NULL COMMENT '所有者ID',
  owner_name VARCHAR(64) NOT NULL COMMENT '所有者名称快照',
  title VARCHAR(500) NOT NULL COMMENT '报告标题',
  report_type VARCHAR(64) NOT NULL COMMENT '报告类型',
  status VARCHAR(32) NOT NULL DEFAULT 'draft' COMMENT '报告状态',
  version_no INT NOT NULL DEFAULT 1 COMMENT '当前版本',
  content LONGTEXT NOT NULL COMMENT 'Markdown正文',
  sections JSON NOT NULL COMMENT '当前结构化章节',
  citations JSON NOT NULL COMMENT '当前版本引用的权威快照',
  quality_issues JSON NOT NULL COMMENT '质量问题',
  metadata_json JSON NOT NULL COMMENT '报告与图形元数据',
  word_count INT NOT NULL DEFAULT 0 COMMENT '字数',
  create_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  update_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
  PRIMARY KEY (report_id),
  CONSTRAINT uk_reports_source_task UNIQUE (source_task_id),
  CONSTRAINT ck_reports_status CHECK (status IN ('draft', 'reviewing', 'completed', 'published', 'archived')),
  CONSTRAINT ck_reports_version_no CHECK (version_no >= 1),
  CONSTRAINT ck_reports_word_count CHECK (word_count >= 0),
  CONSTRAINT fk_reports_generation_tasks FOREIGN KEY (source_task_id) REFERENCES generation_tasks(task_id) ON DELETE SET NULL,
  CONSTRAINT fk_reports_user FOREIGN KEY (user_id) REFERENCES sys_user(user_id) ON DELETE RESTRICT,
  KEY idx_reports_user_type_time (user_id, report_type, update_time),
  KEY idx_reports_user_status_time (user_id, status, update_time)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='科研报告表';

CREATE TABLE IF NOT EXISTS report_versions (
  report_version_id BIGINT NOT NULL AUTO_INCREMENT COMMENT '主键',
  report_id VARCHAR(64) NOT NULL COMMENT '报告ID',
  version_no INT NOT NULL COMMENT '版本号',
  title VARCHAR(500) NOT NULL COMMENT '版本标题',
  content LONGTEXT NOT NULL COMMENT '版本正文',
  sections JSON NOT NULL COMMENT '版本章节',
  citations JSON NOT NULL COMMENT '该版本引用的权威快照',
  quality_issues JSON NOT NULL COMMENT '版本质量问题',
  model_snapshot JSON NOT NULL COMMENT '模型、Prompt和模板快照',
  source VARCHAR(32) NOT NULL DEFAULT 'manual' COMMENT '版本来源',
  operator_id BIGINT NULL COMMENT '操作用户ID',
  operator_name VARCHAR(64) NOT NULL COMMENT '操作用户名称快照',
  create_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  PRIMARY KEY (report_version_id),
  CONSTRAINT uk_report_versions_report_version UNIQUE (report_id, version_no),
  CONSTRAINT ck_report_versions_version_no CHECK (version_no >= 1),
  CONSTRAINT ck_report_versions_source CHECK (source IN ('generated', 'retry', 'manual', 'autosave', 'publish', 'restored')),
  CONSTRAINT fk_report_versions_reports FOREIGN KEY (report_id) REFERENCES reports(report_id) ON DELETE CASCADE,
  CONSTRAINT fk_report_versions_user FOREIGN KEY (operator_id) REFERENCES sys_user(user_id) ON DELETE SET NULL,
  KEY idx_report_versions_report_time (report_id, create_time)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='报告版本表';

CREATE TABLE IF NOT EXISTS report_publications (
  publication_id VARCHAR(64) NOT NULL COMMENT '发布记录ID',
  report_id VARCHAR(64) NOT NULL COMMENT '报告ID',
  report_version_no INT NOT NULL COMMENT '发布时的报告版本号',
  action VARCHAR(16) NOT NULL COMMENT 'publish或unpublish',
  operator_id BIGINT NULL COMMENT '操作用户ID',
  operator_name VARCHAR(64) NOT NULL COMMENT '操作用户名称快照',
  note TEXT NULL COMMENT '发布或撤销说明',
  create_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '操作时间',
  PRIMARY KEY (publication_id),
  CONSTRAINT ck_report_publications_action CHECK (action IN ('publish', 'unpublish')),
  CONSTRAINT ck_report_publications_report_version_no CHECK (report_version_no >= 1),
  CONSTRAINT fk_report_publications_report FOREIGN KEY (report_id) REFERENCES reports(report_id) ON DELETE CASCADE,
  CONSTRAINT fk_report_publications_operator FOREIGN KEY (operator_id) REFERENCES sys_user(user_id) ON DELETE SET NULL,
  KEY idx_report_publications_report_time (report_id, create_time),
  KEY idx_report_publications_action_time (action, create_time)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='报告正式发布与撤销发布审计记录表';

CREATE TABLE IF NOT EXISTS report_exports (
  export_id VARCHAR(64) NOT NULL COMMENT '导出任务ID',
  report_id VARCHAR(64) NOT NULL COMMENT '报告ID',
  user_id BIGINT NOT NULL COMMENT '导出用户ID',
  report_version_no INT NOT NULL COMMENT '报告版本号快照',
  report_revision DATETIME NOT NULL COMMENT '报告修订时间快照',
  format VARCHAR(16) NOT NULL COMMENT '导出格式',
  template_version VARCHAR(64) NULL COMMENT '模板版本快照',
  file_name VARCHAR(500) NOT NULL COMMENT '导出文件名',
  file_key VARCHAR(500) NOT NULL COMMENT '受控存储键',
  content_type VARCHAR(128) NOT NULL COMMENT '文件媒体类型',
  file_size BIGINT NOT NULL DEFAULT 0 COMMENT '文件大小',
  file_hash VARCHAR(128) NULL COMMENT '文件SHA-256',
  snapshot JSON NOT NULL COMMENT '报告导出内容快照',
  status VARCHAR(32) NOT NULL DEFAULT 'queued' COMMENT '导出状态',
  attempt_count INT NOT NULL DEFAULT 0 COMMENT '执行尝试次数',
  lease_owner VARCHAR(128) NULL COMMENT '当前执行器租约持有者',
  lease_until DATETIME NULL COMMENT '当前执行器租约到期时间',
  next_retry_at DATETIME NULL COMMENT '下次重试时间',
  error_message TEXT NULL COMMENT '失败说明',
  create_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  update_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
  completed_time DATETIME NULL COMMENT '完成时间',
  PRIMARY KEY (export_id),
  CONSTRAINT ck_report_exports_format CHECK (format IN ('docx', 'pdf')),
  CONSTRAINT ck_report_exports_status CHECK (status IN ('queued', 'running', 'completed', 'failed')),
  CONSTRAINT ck_report_exports_report_version_no CHECK (report_version_no >= 1),
  CONSTRAINT ck_report_exports_file_size CHECK (file_size >= 0),
  CONSTRAINT ck_report_exports_attempt_count CHECK (attempt_count >= 0),
  CONSTRAINT fk_report_exports_report FOREIGN KEY (report_id) REFERENCES reports(report_id) ON DELETE CASCADE,
  CONSTRAINT fk_report_exports_user FOREIGN KEY (user_id) REFERENCES sys_user(user_id) ON DELETE RESTRICT,
  KEY idx_report_exports_user_report_time (user_id, report_id, create_time),
  KEY idx_report_exports_status_time (status, update_time),
  KEY idx_report_exports_dispatch (status, next_retry_at, lease_until, update_time)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='报告导出任务和文件审计表';
