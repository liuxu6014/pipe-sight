DIGEST_WRITING_RULES = """
简报成文：以事件及其业务影响为主线，先概括本期最值得关注的变化，再在确认的栏目下归纳进展、解释意义及适用边界。不同资料涉及同一事件时合并论述，不按资料编号逐篇复述。
日报突出事件与直接影响；周报比较一周内的进展与联系；月报归纳阶段变化与后续关注。单期资料不能证明长期趋势，不制造“显著提升”等无依据判断。
每个栏目优先写连续的分析段落，必要时使用说明具体主题的小标题。热点分析关闭时不另加研判章节；没有充分依据的可选栏目可省略，不能用空话填满。
"""


def template_writing_prompt(template: dict, report_type: str = '') -> str:
    """兼容旧结构 JSON，但绝不把整份结构配置当作正文写作指令。"""
    prompt = str(template.get('prompt') or '').strip()
    try:
        legacy = json.loads(prompt)
    except (ValueError, TypeError):
        legacy = None
    if isinstance(legacy, dict) and isinstance(legacy.get('sections'), list):
        # 保留管理员在旧配置中明确填写的写作文本；章节由 generation_outline 独立传入。
        prompt = '\n'.join(value.strip() for key in ('prompt', 'instructions', 'description')
                           if isinstance(value := legacy.get(key), str) and value.strip())
    purpose = template.get('purpose') or report_type
    if purpose in {'research', 'article', 'project'}:
        prompt += '\n' + ARTICLE_WRITING_RULES
    if purpose == 'digest' or report_type in {'daily', 'weekly', 'monthly'}:
        prompt += '\n' + DIGEST_WRITING_RULES
    prompt += '\n' + DELIVERY_WRITING_RULES
    prompt += '\n' + EVIDENCE_WRITING_RULES
    return prompt
