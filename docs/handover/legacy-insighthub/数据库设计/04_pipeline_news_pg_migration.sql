-- pipeline_news / news schema 一次性增量迁移
-- PostgreSQL 18.4, pg_partman 5.4.3, pgvector 0.8.5
-- 可重复执行；所有对象创建、约束和权限变更均保持幂等。
-- 保持 news.hp_news 的 RANGE(create_time) 月分区和 ts_hot/ts_cold 分布不变。

\set ON_ERROR_STOP on

BEGIN;

SET LOCAL search_path = news, public;
SET LOCAL lock_timeout = '10s';
SET LOCAL statement_timeout = '5min';

-- 当前 pipeline_news 尚未启用 vector，但服务器已安装 pgvector。
-- 兼容旧部署中 vector 已经装在 public 的情况，统一移动到 news，保证
-- news.vector 和 news.vector_cosine_ops 的引用稳定。
DO $$
DECLARE
    vector_schema text;
BEGIN
    SELECT n.nspname
      INTO vector_schema
      FROM pg_extension e
      JOIN pg_namespace n ON n.oid = e.extnamespace
     WHERE e.extname = 'vector';

    IF vector_schema IS NOT NULL AND vector_schema <> 'news' THEN
        EXECUTE 'ALTER EXTENSION vector SET SCHEMA news';
    END IF;
END
$$;
CREATE EXTENSION IF NOT EXISTS vector WITH SCHEMA news;

-- 领域配置兼容入口：不复制数据，保持现有 sys_domain 读取契约。
CREATE OR REPLACE VIEW news.sys_domain AS
SELECT
    domain_id,
    domain_name,
    remark,
    user_id,
    create_time,
    create_by,
    other,
    del_flag,
    update_time,
    update_by,
    filter_prompts,
    score_prompts,
    return_flag
FROM news.hp_domain;

-- 1. 新闻主表只增加血缘入口；ALTER 父表会自动传播到现有和未来分区。
ALTER TABLE news.hp_news
    ADD COLUMN IF NOT EXISTS prompt_trace_id varchar(26);

COMMENT ON COLUMN news.hp_news.prompt_trace_id IS
    '成功入库新闻的提示词处理血缘 ULID；详细版本记录见 news.news_prompt_usage';

DO $$
BEGIN
    IF EXISTS (
        SELECT 1
        FROM pg_constraint
        WHERE conrelid = 'news.hp_news'::regclass
          AND conname = 'uk_hp_news_prompt_trace_partition'
    ) AND NOT EXISTS (
        SELECT 1
        FROM pg_constraint
        WHERE conrelid = 'news.hp_news'::regclass
          AND conname = 'uk_hp_news_prompt_trace'
    ) THEN
        ALTER TABLE news.hp_news
            RENAME CONSTRAINT uk_hp_news_prompt_trace_partition TO uk_hp_news_prompt_trace;
    ELSIF NOT EXISTS (
        SELECT 1
        FROM pg_constraint
        WHERE conrelid = 'news.hp_news'::regclass
          AND conname = 'uk_hp_news_prompt_trace'
    ) THEN
        ALTER TABLE news.hp_news
            ADD CONSTRAINT uk_hp_news_prompt_trace
            UNIQUE (prompt_trace_id, news_id, create_time);
    END IF;
END
$$;

CREATE INDEX IF NOT EXISTS hp_news_prompt_trace_idx
    ON news.hp_news (prompt_trace_id, create_time);

-- 2. 不可变 Prompt 版本和单父派生关系。
CREATE TABLE IF NOT EXISTS news.sys_prompt_version (
    prompt_version_id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_prompt_version_id  bigint,
    prompt_key                varchar(150) NOT NULL,
    prompt_name               varchar(255) NOT NULL,
    prompt_type               varchar(50) NOT NULL,
    domain_id                 bigint,
    category_id               bigint,
    version_no                integer NOT NULL,
    system_prompt             text NOT NULL DEFAULT '',
    user_prompt               text NOT NULL,
    template_variables        jsonb,
    content_hash              char(64) NOT NULL,
    status                    varchar(20) NOT NULL DEFAULT 'draft',
    derivation_note           varchar(1000),
    created_by                varchar(255),
    created_at                timestamptz NOT NULL DEFAULT now(),
    updated_at                timestamptz NOT NULL DEFAULT now(),
    published_at              timestamptz,

    CONSTRAINT fk_prompt_parent
        FOREIGN KEY (parent_prompt_version_id)
        REFERENCES news.sys_prompt_version (prompt_version_id)
        ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT fk_prompt_domain
        FOREIGN KEY (domain_id)
        REFERENCES news.hp_domain (domain_id)
        ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT fk_prompt_category
        FOREIGN KEY (category_id)
        REFERENCES news.hp_topic (category_id)
        ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT uk_prompt_version
        UNIQUE (prompt_key, version_no),
    CONSTRAINT uk_prompt_content
        UNIQUE (prompt_key, content_hash),
    CONSTRAINT ck_prompt_version_positive
        CHECK (version_no > 0),
    CONSTRAINT ck_prompt_key_not_blank
        CHECK (btrim(prompt_key) <> ''),
    CONSTRAINT ck_prompt_name_not_blank
        CHECK (btrim(prompt_name) <> ''),
    CONSTRAINT ck_prompt_type_not_blank
        CHECK (btrim(prompt_type) <> ''),
    CONSTRAINT ck_prompt_status
        CHECK (status IN ('draft', 'published', 'retired')),
    CONSTRAINT ck_prompt_content_hash_sha256
        CHECK (content_hash ~ '^[0-9a-f]{64}$'),
    CONSTRAINT ck_prompt_not_own_parent
        CHECK (parent_prompt_version_id IS NULL OR parent_prompt_version_id <> prompt_version_id),
    CONSTRAINT ck_prompt_published_at
        CHECK (status <> 'published' OR published_at IS NOT NULL)
);

COMMENT ON TABLE news.sys_prompt_version IS
    '不可变提示词版本；parent_prompt_version_id 支持同 key 演进和跨 key 派生';

CREATE INDEX IF NOT EXISTS idx_prompt_parent
    ON news.sys_prompt_version (parent_prompt_version_id);
CREATE INDEX IF NOT EXISTS idx_prompt_lookup
    ON news.sys_prompt_version (prompt_type, domain_id, category_id, status);
CREATE UNIQUE INDEX IF NOT EXISTS uk_prompt_single_published
    ON news.sys_prompt_version (prompt_key)
    WHERE status = 'published';

-- 3. 成功入库新闻的 Prompt 使用血缘。
-- 使用 prompt_trace_id 作为查询入口，同时携带真实分区主键，不改变 hp_news 分区约束。
CREATE TABLE IF NOT EXISTS news.news_prompt_usage (
    usage_id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    prompt_trace_id    varchar(26) NOT NULL,
    news_id            bigint NOT NULL,
    news_create_time   timestamp without time zone NOT NULL,
    prompt_version_id  bigint NOT NULL,
    stage              varchar(50) NOT NULL,
    sequence_no        integer NOT NULL,
    model_name         varchar(255),
    created_at         timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT fk_prompt_usage_news
        FOREIGN KEY (prompt_trace_id, news_id, news_create_time)
        REFERENCES news.hp_news (prompt_trace_id, news_id, create_time)
        ON UPDATE RESTRICT ON DELETE CASCADE,
    CONSTRAINT fk_prompt_usage_version
        FOREIGN KEY (prompt_version_id)
        REFERENCES news.sys_prompt_version (prompt_version_id)
        ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT uk_prompt_usage_sequence
        UNIQUE (prompt_trace_id, sequence_no),
    CONSTRAINT ck_prompt_usage_trace_not_blank
        CHECK (btrim(prompt_trace_id) <> ''),
    CONSTRAINT ck_prompt_usage_stage_not_blank
        CHECK (btrim(stage) <> ''),
    CONSTRAINT ck_prompt_usage_sequence_positive
        CHECK (sequence_no > 0)
);

COMMENT ON TABLE news.news_prompt_usage IS
    '成功入库新闻实际使用的 Prompt 版本、阶段、顺序和模型';

CREATE INDEX IF NOT EXISTS idx_prompt_usage_version
    ON news.news_prompt_usage (prompt_version_id);
CREATE INDEX IF NOT EXISTS idx_prompt_usage_stage
    ON news.news_prompt_usage (stage, created_at);
CREATE INDEX IF NOT EXISTS idx_prompt_usage_news
    ON news.news_prompt_usage (news_id, news_create_time);
CREATE INDEX IF NOT EXISTS idx_prompt_usage_news_fk
    ON news.news_prompt_usage (prompt_trace_id, news_id, news_create_time);

-- 4. Prompt 更新时间和不可变约束。
CREATE OR REPLACE FUNCTION news.set_updated_at()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.updated_at := now();
    RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION news.guard_prompt_version_immutable()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF OLD.status <> 'draft' AND NEW.status = 'draft' THEN
        RAISE EXCEPTION
            'Prompt version % cannot be reverted to draft after publish', OLD.prompt_version_id
            USING ERRCODE = 'check_violation';
    END IF;

    IF OLD.status <> 'draft'
       OR EXISTS (
            SELECT 1
            FROM news.news_prompt_usage u
            WHERE u.prompt_version_id = OLD.prompt_version_id
       ) THEN
        IF NEW.parent_prompt_version_id IS DISTINCT FROM OLD.parent_prompt_version_id
           OR NEW.prompt_key IS DISTINCT FROM OLD.prompt_key
           OR NEW.prompt_name IS DISTINCT FROM OLD.prompt_name
           OR NEW.prompt_type IS DISTINCT FROM OLD.prompt_type
           OR NEW.domain_id IS DISTINCT FROM OLD.domain_id
           OR NEW.category_id IS DISTINCT FROM OLD.category_id
           OR NEW.version_no IS DISTINCT FROM OLD.version_no
           OR NEW.system_prompt IS DISTINCT FROM OLD.system_prompt
           OR NEW.user_prompt IS DISTINCT FROM OLD.user_prompt
           OR NEW.template_variables IS DISTINCT FROM OLD.template_variables
           OR NEW.content_hash IS DISTINCT FROM OLD.content_hash
           OR NEW.derivation_note IS DISTINCT FROM OLD.derivation_note
           OR NEW.published_at IS DISTINCT FROM OLD.published_at THEN
            RAISE EXCEPTION
                'Prompt version % is immutable after publish or use', OLD.prompt_version_id
                USING ERRCODE = 'check_violation';
        END IF;
    END IF;
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_prompt_version_immutable ON news.sys_prompt_version;
CREATE TRIGGER trg_prompt_version_immutable
BEFORE UPDATE ON news.sys_prompt_version
FOR EACH ROW EXECUTE FUNCTION news.guard_prompt_version_immutable();

DROP TRIGGER IF EXISTS trg_prompt_version_updated_at ON news.sys_prompt_version;
CREATE TRIGGER trg_prompt_version_updated_at
BEFORE UPDATE ON news.sys_prompt_version
FOR EACH ROW EXECUTE FUNCTION news.set_updated_at();

-- 5. 领域-分类与分类标准 Prompt 绑定。
CREATE TABLE IF NOT EXISTS news.act_domain_topic_actions (
    domain_id          bigint NOT NULL,
    category_id        bigint NOT NULL,
    category_prompts   text,
    prompt_version_id  bigint,
    created_at         timestamptz NOT NULL DEFAULT now(),
    updated_at         timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT pk_domain_topic_actions PRIMARY KEY (domain_id, category_id),
    CONSTRAINT fk_domain_topic_domain
        FOREIGN KEY (domain_id) REFERENCES news.hp_domain (domain_id)
        ON UPDATE RESTRICT ON DELETE CASCADE,
    CONSTRAINT fk_domain_topic_category
        FOREIGN KEY (category_id) REFERENCES news.hp_topic (category_id)
        ON UPDATE RESTRICT ON DELETE CASCADE,
    CONSTRAINT fk_domain_topic_prompt_version
        FOREIGN KEY (prompt_version_id) REFERENCES news.sys_prompt_version (prompt_version_id)
        ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT ck_domain_topic_prompt_present
        CHECK (category_prompts IS NOT NULL OR prompt_version_id IS NOT NULL)
);

COMMENT ON TABLE news.act_domain_topic_actions IS
    '领域分类关系；迁移期 category_prompts 与 prompt_version_id 至少一个非空';

DROP TRIGGER IF EXISTS trg_domain_topic_updated_at ON news.act_domain_topic_actions;
CREATE TRIGGER trg_domain_topic_updated_at
BEFORE UPDATE ON news.act_domain_topic_actions
FOR EACH ROW EXECUTE FUNCTION news.set_updated_at();

CREATE INDEX IF NOT EXISTS idx_domain_topic_prompt_version
    ON news.act_domain_topic_actions (prompt_version_id);

-- 6. pgvector 新闻向量表；保留轻量检索快照，不复制正文、摘要和内容提取。
-- 与分区新闻表通过真实复合主键建立同库外键。
CREATE TABLE IF NOT EXISTS news.news_embedding (
    news_id            bigint NOT NULL,
    news_create_time   timestamp without time zone NOT NULL,
    uuid               varchar(255) NOT NULL,
    embedding          news.vector(1024) NOT NULL,
    embedding_model    text NOT NULL,
    embedding_version  integer NOT NULL DEFAULT 1,
    source_hash        char(64) NOT NULL,
    domain_id          bigint,
    category_id        bigint,
    published_at       timestamp without time zone,
    key_words          text NOT NULL DEFAULT '',
    title              varchar(512) NOT NULL,
    ai_title           text NOT NULL DEFAULT '',
    source             varchar(255),
    domain             varchar(255),
    external_link      varchar(4096),
    cover_image_url    varchar(4096),
    producer           varchar(100) NOT NULL DEFAULT 'insight_hub',
    created_at         timestamptz NOT NULL DEFAULT now(),
    updated_at         timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT pk_news_embedding PRIMARY KEY (news_id, news_create_time),
    CONSTRAINT fk_news_embedding_news
        FOREIGN KEY (news_id, news_create_time)
        REFERENCES news.hp_news (news_id, create_time)
        ON UPDATE RESTRICT ON DELETE CASCADE,
    CONSTRAINT ck_news_embedding_uuid_not_blank CHECK (btrim(uuid) <> ''),
    CONSTRAINT ck_news_embedding_title_not_blank CHECK (btrim(title) <> ''),
    CONSTRAINT ck_news_embedding_model_not_blank CHECK (btrim(embedding_model) <> ''),
    CONSTRAINT ck_news_embedding_version_positive CHECK (embedding_version > 0),
    CONSTRAINT ck_news_embedding_source_hash_sha256 CHECK (source_hash ~ '^[0-9a-f]{64}$'),
    CONSTRAINT ck_news_embedding_producer_not_blank CHECK (btrim(producer) <> '')
) TABLESPACE ts_hot;

COMMENT ON TABLE news.news_embedding IS
    '新闻向量、过滤投影和轻量检索快照；向量维度已实测为 1024';

DROP TRIGGER IF EXISTS trg_news_embedding_updated_at ON news.news_embedding;
CREATE TRIGGER trg_news_embedding_updated_at
BEFORE UPDATE ON news.news_embedding
FOR EACH ROW EXECUTE FUNCTION news.set_updated_at();

CREATE INDEX IF NOT EXISTS idx_news_embedding_news_id
    ON news.news_embedding (news_id);
CREATE INDEX IF NOT EXISTS idx_news_embedding_uuid
    ON news.news_embedding (uuid);
CREATE INDEX IF NOT EXISTS idx_news_embedding_domain_published
    ON news.news_embedding (domain_id, published_at DESC);
CREATE INDEX IF NOT EXISTS idx_news_embedding_domain_category_published
    ON news.news_embedding (domain_id, category_id, published_at DESC);
CREATE INDEX IF NOT EXISTS idx_news_embedding_hnsw_cosine
    ON news.news_embedding
    USING hnsw (embedding news.vector_cosine_ops);

-- 7. 应用权限和未来对象默认权限。
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'news_app') THEN
        CREATE ROLE news_app NOLOGIN;
    END IF;
END
$$;

GRANT USAGE ON SCHEMA news TO news_app;
GRANT SELECT, INSERT, UPDATE, DELETE
    ON news.sys_prompt_version,
       news.news_prompt_usage,
       news.act_domain_topic_actions,
       news.news_embedding
    TO news_app;
GRANT SELECT ON news.sys_domain TO news_app;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA news TO news_app;

ALTER DEFAULT PRIVILEGES IN SCHEMA news
    GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO news_app;
ALTER DEFAULT PRIVILEGES IN SCHEMA news
    GRANT USAGE, SELECT ON SEQUENCES TO news_app;

COMMIT;

